def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    if len(sys.argv) == 3 and sys.argv[1] == "--screen":
        capture_named(sys.argv[2])
        return
    for old in OUT.glob("*.png"):
        old.unlink()
    env = os.environ.copy()
    env["PYTHONPATH"] = os.pathsep.join([str(ROOT / "apps" / "api"), str(ROOT / "scripts"), env.get("PYTHONPATH", "")])
    for name in SCREENSHOTS:
        last_error: Exception | None = None
        for attempt in range(1, 3):
            process = subprocess.Popen(
                [sys.executable, str(Path(__file__).resolve()), "--screen", name],
                cwd=ROOT,
                env=env,
                start_new_session=True,
            )
            try:
                return_code = process.wait(timeout=60)
                if return_code == 0 and (OUT / name).exists():
                    last_error = None
                    break
                last_error = RuntimeError(f"worker returned {return_code}")
            except subprocess.TimeoutExpired as exc:
                last_error = exc
                if os.name == "nt":
                    process.kill()
                else:
                    os.killpg(process.pid, signal.SIGKILL)
                process.wait()
            print(f"[screenshots] retry {attempt} for {name}: {last_error}", flush=True)
        if last_error is not None:
            raise RuntimeError(f"Unable to capture {name}") from last_error
    missing = [name for name in SCREENSHOTS if not (OUT / name).exists()]
    if missing:
        raise RuntimeError(f"Missing screenshots: {missing}")
    print(f"Captured {len(SCREENSHOTS)} screenshots in {OUT}")


if __name__ == "__main__":
    main()
